    mm [command] [args]

COMMANDS:
    mm init [dir]       Initialize project configuration
    mm                  Start full workspace (apps + AI)
    mm ai               Start AI workstation only
    mm stop             Stop workspace applications
    mm exec <cmd>       Execute custom command
    mm list             List available commands
    mm help             Show this help message
    mm version          Show version information

CONFIGURATION:
    Configuration file: ~/.mmrc
    Edit this file to customize your project settings.

FOR MORE INFORMATION:
    https://github.com/ai-dev-workstation/ai-dev-workstation
EOF
}
